  from lessons
  join units on units.id = lessons.unit_id
  join languages on languages.id = units.language_id
  where languages.code = 'en' and units.position = 12 and lessons.position = 8;

  if v_lesson_id is null then
    raise notice 'Leçon Unité 12 / position 8 introuvable, ignorée.';
    return;
  end if;

  select count(*) into v_count from exercises where lesson_id = v_lesson_id;
  update exercises set position = position * 2 where lesson_id = v_lesson_id;

  v_slot1 := floor(v_count * 2 * 0.33)::int;
  if v_slot1 % 2 = 0 then v_slot1 := v_slot1 + 1; end if;
  v_slot1 := greatest(v_slot1, 1);

  v_slot2 := floor(v_count * 2 * 0.66)::int;
  if v_slot2 % 2 = 0 then v_slot2 := v_slot2 + 1; end if;
  v_slot2 := greatest(v_slot2, v_slot1 + 2);

  insert into exercises (lesson_id, type, position, content) values
    (v_lesson_id, 'speaking_practice', v_slot1, '{"sentence": "How many times have you been abroad?", "sentence_fr": "Combien de fois es-tu allé à l''étranger ?", "tip": "\"How many times\" + present perfect pour compter les expériences."}'::jsonb),
    (v_lesson_id, 'speaking_practice', v_slot2, '{"sentence": "I''ve traveled to five different countries.", "sentence_fr": "J''ai voyagé dans cinq pays différents.", "tip": "\"Traveled\" avec un seul \"l\" en anglais américain."}'::jsonb);
end $$;
