do $$
declare
  v_lesson_id uuid;
  v_count int;
  v_slot1 int;
  v_slot2 int;
begin
  select lessons.id into v_lesson_id
  from lessons
  join units on units.id = lessons.unit_id
  join languages on languages.id = units.language_id
  where languages.code = 'en' and units.position = 4 and lessons.position = 1;

  if v_lesson_id is null then
    raise notice 'Leçon Unité 4 / position 1 introuvable, ignorée.';
    return;
  end if;

  select count(*) into v_count from exercises where lesson_id = v_lesson_id;
  update exercises set position = position * 2 where lesson_id = v_lesson_id;

  v_slot1 := floor(v_count * 2 * 0.33)::int;
  if v_slot1 % 2 = 0 then v_slot1 := v_slot1 + 1; end if;
  v_slot1 := greatest(v_slot1, 1);

  v_slot2 := floor(v_count * 2 * 0.66)::int;
  if v_slot2 % 2 = 0 then v_slot2 := v_slot2 + 1; end if;
  v_slot2 := greatest(v_slot2, v_slot1 + 2);

  insert into exercises (lesson_id, type, position, content) values
    (v_lesson_id, 'speaking_practice', v_slot1, '{"sentence": "This is my car.", "sentence_fr": "C''est ma voiture.", "tip": "\"My\" se prononce \"mai\", comme \"my\" en un seul son clair."}'::jsonb),
    (v_lesson_id, 'speaking_practice', v_slot2, '{"sentence": "Is that your bag?", "sentence_fr": "C''est ton sac ?", "tip": "\"Your\" se prononce \"yor\", assez court, pas \"you-a\"."}'::jsonb);
end $$;


